void	ft_rev_int_tab(int *tab, int size)
{
	int	*tab2;
	int	tmp;

	tab2 = tab + size - 1;
	while (tab2 > tab)
	{
		tmp = *tab;
		*tab = *tab2;
		*tab2 = tmp;
		tab++;
		tab2--;
	}
}
