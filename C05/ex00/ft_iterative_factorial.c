int	ft_iterative_factorial(int nb)
{
	int	i;
	int	ft;

	if (nb < 0)
		return (0);
	ft = 1;
	i = 1;
	while (i <= nb)
	{
		ft = ft * i;
		i++;
	}
	return (ft);
}
